/**
 * Local GitHub/git workflow helpers — summarize, explain diffs, draft commit/PR text.
 * Never auto-pushes.
 */
const { execSync } = require('child_process');
const config = require('../config');

function runGit(args) {
  try {
    return execSync(`git ${args}`, {
      cwd: config.workspaceRoot,
      encoding: 'utf8',
      timeout: 60000,
      stdio: ['pipe', 'pipe', 'pipe'],
    }).trim();
  } catch (e) {
    return String(e.stdout || e.stderr || e.message || '').trim();
  }
}

function summarizeRepo() {
  const branch = runGit('rev-parse --abbrev-ref HEAD') || 'unknown';
  const status = runGit('status --short') || '(clean)';
  const aheadBehind = runGit('status -sb').split('\n')[0] || '';
  const last = runGit('log -5 --oneline') || '(no commits)';
  const remotes = runGit('remote -v') || '(no remotes)';
  return {
    ok: true,
    branch,
    aheadBehind,
    status,
    recentCommits: last,
    remotes,
    markdown: `# Repository state

**Branch:** ${branch}
**Tracking:** ${aheadBehind}

## Working tree
\`\`\`
${status}
\`\`\`

## Recent commits
\`\`\`
${last}
\`\`\`

## Remotes
\`\`\`
${remotes}
\`\`\`

Tony will not push unless you approve.
`,
  };
}

function explainChangedFiles() {
  const names = runGit('diff --name-status HEAD').split('\n').filter(Boolean);
  const staged = runGit('diff --cached --name-status').split('\n').filter(Boolean);
  const untracked = runGit('ls-files --others --exclude-standard')
    .split('\n')
    .filter(Boolean)
    .map((f) => `?\t${f}`);
  const all = [...staged.map((l) => `STAGED ${l}`), ...names.map((l) => `UNSTAGED ${l}`), ...untracked.map((l) => `UNTRACKED ${l}`)];
  const explanations = all.slice(0, 40).map((line) => {
    const parts = line.split(/\s+/);
    const tag = parts[0];
    const code = parts[1] || '';
    const file = parts.slice(2).join(' ') || parts[1] || line;
    const verb =
      code.startsWith('A') || tag === 'UNTRACKED'
        ? 'Added'
        : code.startsWith('D')
          ? 'Deleted'
          : code.startsWith('R')
            ? 'Renamed'
            : 'Modified';
    return `- **${verb}** \`${file}\` (${tag.toLowerCase()})`;
  });
  return {
    ok: true,
    count: all.length,
    files: all,
    markdown: `# Changed files (${all.length})

${explanations.join('\n') || '- No local changes detected.'}

Use this before commit/push. Approval still required for git write actions.
`,
  };
}

function generateCommitMessage(topic = '') {
  const names = runGit('diff --name-only HEAD').split('\n').filter(Boolean);
  const staged = runGit('diff --cached --name-only').split('\n').filter(Boolean);
  const files = [...new Set([...staged, ...names])].slice(0, 12);
  const focus = topic || inferTopic(files);
  const body = files.length
    ? files.map((f) => `- touch ${f}`).join('\n')
    : '- document local operator updates';
  const message = `feat: ${focus}

${body}

Generated by TONY (draft only — review before commit).`;
  return { ok: true, message, files, draftOnly: true };
}

function preparePrInstructions(topic = '') {
  const branch = runGit('rev-parse --abbrev-ref HEAD') || 'feature-branch';
  const commit = generateCommitMessage(topic || 'operator improvements');
  const changed = explainChangedFiles();
  const markdown = `# Push / PR checklist (manual)

1. Review changed files:
${changed.markdown}

2. Suggested commit message:
\`\`\`
${commit.message}
\`\`\`

3. Commands (Tony will ask approval before running push):
\`\`\`bash
git add -A
git commit -m "$(cat <<'EOF'
${commit.message}
EOF
)"
git push -u origin ${branch}
\`\`\`

4. Open PR against your preferred base (usually \`master\`) with:
   - Title: ${commit.message.split('\n')[0]}
   - Body: summary of operator/intent/safety changes + test proof (\`npm test\`)

Tony does **not** auto-push or auto-create the PR unless you approve.
`;
  return { ok: true, branch, commit, changed, markdown, draftOnly: true };
}

function inferTopic(files) {
  const joined = files.join(' ').toLowerCase();
  if (joined.includes('intent')) return 'improve intent routing';
  if (joined.includes('safety') || joined.includes('approval')) return 'strengthen safety approvals';
  if (joined.includes('jarvis') || joined.includes('public/')) return 'upgrade JARVIS operator UI';
  if (joined.includes('voice')) return 'improve voice pipeline';
  if (joined.includes('github')) return 'expand GitHub workflow helpers';
  return 'expand TONY operator capabilities';
}

function runGh(args) {
  try {
    const out = execSync(`gh ${args}`, {
      cwd: config.workspaceRoot,
      encoding: 'utf8',
      timeout: 120000,
      stdio: ['pipe', 'pipe', 'pipe'],
      env: { ...process.env, ...(config.githubToken ? { GH_TOKEN: config.githubToken } : {}) },
    });
    return { ok: true, output: String(out).trim() };
  } catch (e) {
    return {
      ok: false,
      error: String(e.stderr || e.stdout || e.message || 'gh failed').trim(),
    };
  }
}

function createIssue({ title, body = '', labels = [] } = {}) {
  if (!title?.trim()) return { ok: false, error: 'Issue title required' };
  const labelFlags = (labels || []).map((l) => `--label ${JSON.stringify(l)}`).join(' ');
  const cmd = `issue create --title ${JSON.stringify(title)} --body ${JSON.stringify(body || 'Created by TONY')} ${labelFlags}`.trim();
  const result = runGh(cmd);
  return { ...result, draftOnly: false, action: 'create_issue' };
}

function createPullRequest({ title, body = '', base = 'master', draft = false } = {}) {
  if (!title?.trim()) {
    title = generateCommitMessage().message.split('\n')[0].replace(/^feat:\s*/i, '') || 'Tony update';
  }
  const draftFlag = draft ? '--draft' : '';
  const cmd = `pr create --title ${JSON.stringify(title)} --body ${JSON.stringify(
    body || 'Created by TONY after approval/trusted mode.'
  )} --base ${JSON.stringify(base)} ${draftFlag}`.trim();
  const result = runGh(cmd);
  return { ...result, action: 'create_pr', base, draft: Boolean(draft) };
}

module.exports = {
  summarizeRepo,
  explainChangedFiles,
  generateCommitMessage,
  preparePrInstructions,
  createIssue,
  createPullRequest,
  runGh,
};
